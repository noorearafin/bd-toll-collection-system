            SELECT 'TRK_M',1250,0 FROM dual UNION ALL SELECT 'TRK_L',1600,0 FROM dual UNION ALL
            SELECT 'TRK_3A',2000,0 FROM dual UNION ALL SELECT 'TRL_4A',3000,0 FROM dual UNION ALL
            SELECT 'TRL_XA',4000,1000 FROM dual) LOOP
