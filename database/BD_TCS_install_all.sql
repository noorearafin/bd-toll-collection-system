  FUNCTION current_emp_id (p_username IN VARCHAR2 DEFAULT NULL) RETURN NUMBER IS
    l_user   VARCHAR2(255) := UPPER(COALESCE(p_username, SYS_CONTEXT('APEX$SESSION', 'APP_USER'), USER));
    l_emp_id NUMBER;
  BEGIN
    SELECT emp_id
