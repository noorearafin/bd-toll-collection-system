-- =====================================================================
--  Bangladesh Toll Collection System (BD-TCS)
--  01_tables.sql  -  Tables, keys, constraints and indexes
--  Target : Oracle Database 19c / 23ai  (apex.oracle.com workspace)
--  Notes  : * Money is in Bangladeshi Taka (BDT), 2 decimals
--           * Mobile numbers follow the BTRC 11-digit format 01[3-9]XXXXXXXX
--           * NID accepts 10, 13 or 17 digit Bangladesh National ID numbers
--           * Vehicle plate follows BRTA style  AREA-LETTER SS-NNNN
--             e.g. DHAKA METRO-GA 12-3456
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. LOCATION
-- ---------------------------------------------------------------------
CREATE TABLE tc_division (
  division_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_division_pk PRIMARY KEY,
  division_name     VARCHAR2(50 CHAR) NOT NULL CONSTRAINT tc_division_name_uk UNIQUE,
  division_name_bn  VARCHAR2(50 CHAR)
);

CREATE TABLE tc_district (
  district_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_district_pk PRIMARY KEY,
  division_id       NUMBER NOT NULL CONSTRAINT tc_district_division_fk REFERENCES tc_division (division_id),
  district_name     VARCHAR2(50 CHAR) NOT NULL CONSTRAINT tc_district_name_uk UNIQUE,
  district_name_bn  VARCHAR2(50 CHAR)
);

-- ---------------------------------------------------------------------
-- 2. INFRASTRUCTURE & TARIFF
-- ---------------------------------------------------------------------
CREATE TABLE tc_authority (
  authority_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_authority_pk PRIMARY KEY,
  authority_code    VARCHAR2(10 CHAR) NOT NULL CONSTRAINT tc_authority_code_uk UNIQUE,
  authority_name    VARCHAR2(150 CHAR) NOT NULL,
  authority_name_bn VARCHAR2(150 CHAR),
  hotline           VARCHAR2(20 CHAR),
  website           VARCHAR2(200 CHAR)
);

CREATE TABLE tc_toll_plaza (
  plaza_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_plaza_pk PRIMARY KEY,
  plaza_code        VARCHAR2(10 CHAR) NOT NULL CONSTRAINT tc_plaza_code_uk UNIQUE
                    CONSTRAINT tc_plaza_code_ck CHECK (REGEXP_LIKE(plaza_code, '^[A-Z0-9-]+$')),
  plaza_name        VARCHAR2(150 CHAR) NOT NULL,
  plaza_name_bn     VARCHAR2(150 CHAR),
  facility_type     VARCHAR2(12 CHAR) NOT NULL
                    CONSTRAINT tc_plaza_type_ck CHECK (facility_type IN ('BRIDGE','TUNNEL','EXPRESSWAY','HIGHWAY')),
  location_desc     VARCHAR2(200 CHAR),
  district_id       NUMBER NOT NULL CONSTRAINT tc_plaza_district_fk REFERENCES tc_district (district_id),
  authority_id      NUMBER NOT NULL CONSTRAINT tc_plaza_authority_fk REFERENCES tc_authority (authority_id),
  opened_on         DATE,
  is_active         CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT tc_plaza_active_ck CHECK (is_active IN ('Y','N'))
);

CREATE TABLE tc_toll_lane (
  lane_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_lane_pk PRIMARY KEY,
  plaza_id          NUMBER NOT NULL CONSTRAINT tc_lane_plaza_fk REFERENCES tc_toll_plaza (plaza_id),
  lane_no           NUMBER(3) NOT NULL CONSTRAINT tc_lane_no_ck CHECK (lane_no > 0),
  direction         VARCHAR2(40 CHAR) NOT NULL,
  lane_type         VARCHAR2(6 CHAR) DEFAULT 'HYBRID' NOT NULL
                    CONSTRAINT tc_lane_type_ck CHECK (lane_type IN ('MTC','ETC','HYBRID')),
  is_active         CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT tc_lane_active_ck CHECK (is_active IN ('Y','N')),
  CONSTRAINT tc_lane_plaza_no_uk UNIQUE (plaza_id, lane_no)
);
COMMENT ON COLUMN tc_toll_lane.lane_type IS 'MTC = Manual Toll Collection, ETC = Electronic (RFID) only, HYBRID = both';

CREATE TABLE tc_vehicle_class (
  class_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_class_pk PRIMARY KEY,
  class_code        VARCHAR2(10 CHAR) NOT NULL CONSTRAINT tc_class_code_uk UNIQUE,
  class_name        VARCHAR2(100 CHAR) NOT NULL,
  class_name_bn     VARCHAR2(100 CHAR),
  description       VARCHAR2(400 CHAR),
  min_axles         NUMBER(2) DEFAULT 2 NOT NULL,
  max_axles         NUMBER(2) DEFAULT 2 NOT NULL,
  sort_order        NUMBER(3),
  CONSTRAINT tc_class_axles_ck CHECK (min_axles >= 2 AND max_axles >= min_axles)
);

CREATE TABLE tc_toll_rate (
  rate_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_rate_pk PRIMARY KEY,
  plaza_id          NUMBER NOT NULL CONSTRAINT tc_rate_plaza_fk REFERENCES tc_toll_plaza (plaza_id),
  class_id          NUMBER NOT NULL CONSTRAINT tc_rate_class_fk REFERENCES tc_vehicle_class (class_id),
  toll_amount       NUMBER(10,2) NOT NULL CONSTRAINT tc_rate_amount_ck CHECK (toll_amount >= 0),
  extra_axle_amount NUMBER(10,2) DEFAULT 0 NOT NULL CONSTRAINT tc_rate_extra_ck CHECK (extra_axle_amount >= 0),
  effective_from    DATE NOT NULL,
  effective_to      DATE,
  reference_note    VARCHAR2(400 CHAR),
  CONSTRAINT tc_rate_uk UNIQUE (plaza_id, class_id, effective_from),
  CONSTRAINT tc_rate_dates_ck CHECK (effective_to IS NULL OR effective_to > effective_from)
);
COMMENT ON COLUMN tc_toll_rate.extra_axle_amount IS 'Charged for every axle above tc_vehicle_class.min_axles';

CREATE TABLE tc_payment_method (
  method_code       VARCHAR2(10 CHAR) CONSTRAINT tc_method_pk PRIMARY KEY,
  method_name       VARCHAR2(60 CHAR) NOT NULL,
  method_name_bn    VARCHAR2(60 CHAR),
  is_mfs            CHAR(1) DEFAULT 'N' NOT NULL CONSTRAINT tc_method_mfs_ck CHECK (is_mfs IN ('Y','N')),
  is_active         CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT tc_method_active_ck CHECK (is_active IN ('Y','N'))
);
COMMENT ON COLUMN tc_payment_method.is_mfs IS 'Y = Mobile Financial Service (bKash, Nagad, Rocket ...)';

CREATE TABLE tc_exemption_type (
  exemption_code    VARCHAR2(20 CHAR) CONSTRAINT tc_exempt_pk PRIMARY KEY,
  description       VARCHAR2(200 CHAR) NOT NULL,
  description_bn    VARCHAR2(200 CHAR),
  legal_basis       VARCHAR2(400 CHAR),
  doc_required      CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT tc_exempt_doc_ck CHECK (doc_required IN ('Y','N')),
  is_active         CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT tc_exempt_active_ck CHECK (is_active IN ('Y','N'))
);

-- ---------------------------------------------------------------------
-- 3. VEHICLES, OWNERS & ETC (RFID) ACCOUNTS
-- ---------------------------------------------------------------------
CREATE TABLE tc_owner (
  owner_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_owner_pk PRIMARY KEY,
  owner_type        VARCHAR2(12 CHAR) DEFAULT 'INDIVIDUAL' NOT NULL
                    CONSTRAINT tc_owner_type_ck CHECK (owner_type IN ('INDIVIDUAL','COMPANY','GOVERNMENT')),
  full_name         VARCHAR2(150 CHAR) NOT NULL,
  nid               VARCHAR2(17 CHAR) CONSTRAINT tc_owner_nid_uk UNIQUE
                    CONSTRAINT tc_owner_nid_ck CHECK (REGEXP_LIKE(nid, '^([0-9]{10}|[0-9]{13}|[0-9]{17})$')),
  trade_license_no  VARCHAR2(30 CHAR),
  mobile            VARCHAR2(11 CHAR) NOT NULL
                    CONSTRAINT tc_owner_mobile_ck CHECK (REGEXP_LIKE(mobile, '^01[3-9][0-9]{8}$')),
  email             VARCHAR2(150 CHAR)
                    CONSTRAINT tc_owner_email_ck CHECK (REGEXP_LIKE(email, '^[^@ ]+@[^@ ]+\.[^@ ]+$')),
  address           VARCHAR2(400 CHAR),
  district_id       NUMBER CONSTRAINT tc_owner_district_fk REFERENCES tc_district (district_id),
  CONSTRAINT tc_owner_id_doc_ck CHECK (owner_type <> 'INDIVIDUAL' OR nid IS NOT NULL)
);

CREATE TABLE tc_vehicle (
  vehicle_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_vehicle_pk PRIMARY KEY,
  reg_area          VARCHAR2(30 CHAR) NOT NULL
                    CONSTRAINT tc_vehicle_area_ck CHECK (REGEXP_LIKE(reg_area, '^[A-Z]+( [A-Z]+)?$')),
  reg_letter        VARCHAR2(4 CHAR) NOT NULL
                    CONSTRAINT tc_vehicle_letter_ck CHECK (REGEXP_LIKE(reg_letter, '^[A-Z]{1,4}$')),
  reg_series        VARCHAR2(2 CHAR) NOT NULL
                    CONSTRAINT tc_vehicle_series_ck CHECK (REGEXP_LIKE(reg_series, '^[0-9]{2}$')),
  reg_number        VARCHAR2(4 CHAR) NOT NULL
                    CONSTRAINT tc_vehicle_number_ck CHECK (REGEXP_LIKE(reg_number, '^[0-9]{4}$')),
  reg_no            VARCHAR2(60 CHAR) GENERATED ALWAYS AS
                    (reg_area || '-' || reg_letter || ' ' || reg_series || '-' || reg_number) VIRTUAL,
  class_id          NUMBER NOT NULL CONSTRAINT tc_vehicle_class_fk REFERENCES tc_vehicle_class (class_id),
  owner_id          NUMBER NOT NULL CONSTRAINT tc_vehicle_owner_fk REFERENCES tc_owner (owner_id),
  make_model        VARCHAR2(100 CHAR),
  color             VARCHAR2(30 CHAR),
  manufacture_year  NUMBER(4) CONSTRAINT tc_vehicle_year_ck CHECK (manufacture_year BETWEEN 1950 AND 2100),
  fitness_expiry    DATE,
  tax_token_expiry  DATE,
  status            VARCHAR2(12 CHAR) DEFAULT 'ACTIVE' NOT NULL
                    CONSTRAINT tc_vehicle_status_ck CHECK (status IN ('ACTIVE','BLACKLISTED','INACTIVE')),
  CONSTRAINT tc_vehicle_regno_uk UNIQUE (reg_no)
);
COMMENT ON COLUMN tc_vehicle.reg_no IS 'Virtual column - BRTA style plate, e.g. DHAKA METRO-GA 12-3456';

CREATE TABLE tc_etc_tag (
  tag_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_tag_pk PRIMARY KEY,
  tag_uid           VARCHAR2(24 CHAR) NOT NULL CONSTRAINT tc_tag_uid_uk UNIQUE
                    CONSTRAINT tc_tag_uid_ck CHECK (REGEXP_LIKE(tag_uid, '^[0-9A-F]{24}$')),
  vehicle_id        NUMBER NOT NULL CONSTRAINT tc_tag_vehicle_fk REFERENCES tc_vehicle (vehicle_id),
  balance           NUMBER(12,2) DEFAULT 0 NOT NULL CONSTRAINT tc_tag_balance_ck CHECK (balance >= 0),
  low_balance_limit NUMBER(10,2) DEFAULT 500 NOT NULL,
  issued_on         DATE DEFAULT SYSDATE NOT NULL,
  status            VARCHAR2(10 CHAR) DEFAULT 'ACTIVE' NOT NULL
                    CONSTRAINT tc_tag_status_ck CHECK (status IN ('ACTIVE','BLOCKED','LOST','EXPIRED'))
);
COMMENT ON COLUMN tc_etc_tag.tag_uid IS '96-bit RFID EPC written as 24 hex characters';

CREATE TABLE tc_tag_recharge (
  recharge_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_recharge_pk PRIMARY KEY,
  tag_id            NUMBER NOT NULL CONSTRAINT tc_recharge_tag_fk REFERENCES tc_etc_tag (tag_id),
  amount            NUMBER(10,2) NOT NULL CONSTRAINT tc_recharge_amount_ck CHECK (amount > 0 AND amount <= 100000),
  method_code       VARCHAR2(10 CHAR) NOT NULL CONSTRAINT tc_recharge_method_fk REFERENCES tc_payment_method (method_code),
  provider_txn_ref  VARCHAR2(40 CHAR),
  recharged_at      DATE DEFAULT SYSDATE NOT NULL,
  recharged_by      VARCHAR2(255 CHAR),
  CONSTRAINT tc_recharge_method_ck CHECK (method_code <> 'ETC')
);

-- ---------------------------------------------------------------------
-- 4. OPERATIONS: STAFF, SHIFTS, TRANSACTIONS, VIOLATIONS
-- ---------------------------------------------------------------------
CREATE TABLE tc_employee (
  emp_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_employee_pk PRIMARY KEY,
  emp_code          VARCHAR2(10 CHAR) NOT NULL CONSTRAINT tc_employee_code_uk UNIQUE,
  full_name         VARCHAR2(150 CHAR) NOT NULL,
  nid               VARCHAR2(17 CHAR) NOT NULL CONSTRAINT tc_employee_nid_uk UNIQUE
                    CONSTRAINT tc_employee_nid_ck CHECK (REGEXP_LIKE(nid, '^([0-9]{10}|[0-9]{13}|[0-9]{17})$')),
  mobile            VARCHAR2(11 CHAR) NOT NULL
                    CONSTRAINT tc_employee_mobile_ck CHECK (REGEXP_LIKE(mobile, '^01[3-9][0-9]{8}$')),
  designation       VARCHAR2(15 CHAR) NOT NULL
                    CONSTRAINT tc_employee_desig_ck CHECK (designation IN ('TOLL_COLLECTOR','SUPERVISOR','PLAZA_MANAGER','ADMIN')),
  plaza_id          NUMBER CONSTRAINT tc_employee_plaza_fk REFERENCES tc_toll_plaza (plaza_id),
  apex_username     VARCHAR2(255 CHAR) CONSTRAINT tc_employee_user_uk UNIQUE,
  joining_date      DATE,
  is_active         CHAR(1) DEFAULT 'Y' NOT NULL CONSTRAINT tc_employee_active_ck CHECK (is_active IN ('Y','N')),
  CONSTRAINT tc_employee_plaza_ck CHECK (designation = 'ADMIN' OR plaza_id IS NOT NULL)
);
COMMENT ON COLUMN tc_employee.apex_username IS 'APEX login name - used for role based authorization';

CREATE TABLE tc_shift (
  shift_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_shift_pk PRIMARY KEY,
  lane_id           NUMBER NOT NULL CONSTRAINT tc_shift_lane_fk REFERENCES tc_toll_lane (lane_id),
  emp_id            NUMBER NOT NULL CONSTRAINT tc_shift_emp_fk REFERENCES tc_employee (emp_id),
  shift_code        CHAR(1) NOT NULL CONSTRAINT tc_shift_code_ck CHECK (shift_code IN ('A','B','C')),
  shift_date        DATE NOT NULL,
  opened_at         DATE NOT NULL,
  closed_at         DATE,
  opening_float     NUMBER(10,2) DEFAULT 0 NOT NULL CONSTRAINT tc_shift_float_ck CHECK (opening_float >= 0),
  declared_cash     NUMBER(12,2),
  system_cash       NUMBER(12,2),
  cash_variance     NUMBER(12,2),
  status            VARCHAR2(6 CHAR) DEFAULT 'OPEN' NOT NULL CONSTRAINT tc_shift_status_ck CHECK (status IN ('OPEN','CLOSED')),
  closed_by         NUMBER CONSTRAINT tc_shift_closed_by_fk REFERENCES tc_employee (emp_id),
  remarks           VARCHAR2(400 CHAR),
  CONSTRAINT tc_shift_close_ck CHECK (
        (status = 'OPEN'   AND closed_at IS NULL)
     OR (status = 'CLOSED' AND closed_at IS NOT NULL AND declared_cash IS NOT NULL AND closed_at >= opened_at))
);
COMMENT ON COLUMN tc_shift.shift_code IS 'A = 06:00-14:00, B = 14:00-22:00, C = 22:00-06:00 (Bangladesh time)';

-- only ONE open shift per lane and per employee at any time
CREATE UNIQUE INDEX tc_shift_open_lane_ux ON tc_shift (CASE WHEN status = 'OPEN' THEN lane_id END);
CREATE UNIQUE INDEX tc_shift_open_emp_ux  ON tc_shift (CASE WHEN status = 'OPEN' THEN emp_id END);
-- only ONE active RFID tag per vehicle
CREATE UNIQUE INDEX tc_tag_one_active_ux  ON tc_etc_tag (CASE WHEN status = 'ACTIVE' THEN vehicle_id END);

CREATE SEQUENCE tc_toll_txn_seq START WITH 1 INCREMENT BY 1 CACHE 50;

CREATE TABLE tc_toll_txn (
  txn_id            NUMBER DEFAULT tc_toll_txn_seq.NEXTVAL CONSTRAINT tc_txn_pk PRIMARY KEY,
  receipt_no        VARCHAR2(40 CHAR) NOT NULL CONSTRAINT tc_txn_receipt_uk UNIQUE,
  shift_id          NUMBER NOT NULL CONSTRAINT tc_txn_shift_fk REFERENCES tc_shift (shift_id),
  rate_id           NUMBER NOT NULL CONSTRAINT tc_txn_rate_fk REFERENCES tc_toll_rate (rate_id),
  vehicle_id        NUMBER CONSTRAINT tc_txn_vehicle_fk REFERENCES tc_vehicle (vehicle_id),
  captured_reg_no   VARCHAR2(60 CHAR) NOT NULL,
  axle_count        NUMBER(2) DEFAULT 2 NOT NULL CONSTRAINT tc_txn_axle_ck CHECK (axle_count BETWEEN 2 AND 12),
  toll_amount       NUMBER(10,2) NOT NULL CONSTRAINT tc_txn_amount_ck CHECK (toll_amount >= 0),
  method_code       VARCHAR2(10 CHAR) CONSTRAINT tc_txn_method_fk REFERENCES tc_payment_method (method_code),
  tag_id            NUMBER CONSTRAINT tc_txn_tag_fk REFERENCES tc_etc_tag (tag_id),
  payment_ref       VARCHAR2(40 CHAR),
  exemption_code    VARCHAR2(20 CHAR) CONSTRAINT tc_txn_exempt_fk REFERENCES tc_exemption_type (exemption_code),
  exemption_doc_ref VARCHAR2(60 CHAR),
  txn_time          DATE NOT NULL,
  status            VARCHAR2(6 CHAR) DEFAULT 'PAID' NOT NULL CONSTRAINT tc_txn_status_ck CHECK (status IN ('PAID','EXEMPT','VOID')),
  void_reason       VARCHAR2(200 CHAR),
  voided_by         NUMBER CONSTRAINT tc_txn_voided_by_fk REFERENCES tc_employee (emp_id),
  -- either a payment method OR an exemption, never both
  CONSTRAINT tc_txn_pay_or_exempt_ck CHECK (
        (exemption_code IS NULL AND method_code IS NOT NULL)
     OR (exemption_code IS NOT NULL AND method_code IS NULL AND toll_amount = 0)),
  CONSTRAINT tc_txn_etc_tag_ck  CHECK (method_code IS NULL OR method_code <> 'ETC' OR tag_id IS NOT NULL),
  CONSTRAINT tc_txn_void_ck     CHECK (status <> 'VOID' OR void_reason IS NOT NULL)
);
COMMENT ON COLUMN tc_toll_txn.captured_reg_no IS 'Plate as captured at the lane (vehicle_id is filled when the plate is registered in the system)';

CREATE TABLE tc_violation (
  violation_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY CONSTRAINT tc_violation_pk PRIMARY KEY,
  shift_id          NUMBER NOT NULL CONSTRAINT tc_violation_shift_fk REFERENCES tc_shift (shift_id),
  txn_id            NUMBER CONSTRAINT tc_violation_txn_fk REFERENCES tc_toll_txn (txn_id),
  vehicle_id        NUMBER CONSTRAINT tc_violation_vehicle_fk REFERENCES tc_vehicle (vehicle_id),
  captured_reg_no   VARCHAR2(60 CHAR) NOT NULL,
  violation_type    VARCHAR2(20 CHAR) NOT NULL
                    CONSTRAINT tc_violation_type_ck CHECK (violation_type IN
                      ('TOLL_EVASION','LOW_ETC_BALANCE','CLASS_MISMATCH','OVERLOAD','BLACKLISTED','BARRIER_DAMAGE')),
  detected_at       DATE NOT NULL,
  fine_amount       NUMBER(10,2) DEFAULT 0 NOT NULL CONSTRAINT tc_violation_fine_ck CHECK (fine_amount >= 0),
  status            VARCHAR2(10 CHAR) DEFAULT 'OPEN' NOT NULL
                    CONSTRAINT tc_violation_status_ck CHECK (status IN ('OPEN','PAID','WAIVED','REFERRED')),
  remarks           VARCHAR2(400 CHAR)
);

